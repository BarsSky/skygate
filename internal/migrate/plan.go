// plan.go — the cutover catalog (B482): every step of a host migration as data.
//
// # WHY A CATALOG AND NOT A SCRIPT
//
// The 2026-11-15/16 cutover was 44 manual steps and it left no commits: the knowledge lived in a
// chat log, and the same installation cannot be rebuilt from the repository if the host is lost
// (TD-38). The operator asked for the analysis to become a wizard in the panel, where each answer
// is a question with a choice or an input and the application is automatic. A wizard needs the
// steps as data — ordered, typed, parameterised by the answers, and testable without a network —
// which is exactly this file: `docs/host-migration.md` §3 is the prose version of the same list.
//
// WHAT A STEP IS
//
//	Where   local    runs on THIS host (the panel that is being replaced);
//	        remote   runs on the NEW host over the wizard's SSH session;
//	        copy     streams a local path to the new host (tar over the SSH session);
//	        internal a panel action with no shell: a DB row, a headscale API call, an ACL push;
//	        manual   the wizard only shows the instruction — a browser click, a TTL wait, or a
//	                 decision only the operator can make.
//	Kind    auto     runs unattended;
//	        confirm  runs only after the operator confirmed the step's own risk note;
//	        manual   never runs.
//
// A step's `Verify` is a command that must exit 0; for internal steps it is a named assertion the
// runner knows how to make. `Why` is the i18n key that explains the failure mode behind the step,
// because "copy the noise key" is useless advice without "otherwise every client re-registers".
package migrate

import (
	"fmt"
	"net/netip"
	"strings"
)

// Where a step executes.
const (
	WhereLocal    = "local"
	WhereRemote   = "remote"
	WhereCopy     = "copy"
	WhereInternal = "internal"
	WhereManual   = "manual"
	// WhereScript runs an EMBEDDED helper on the new host (B487): the body travels in the binary and is
	// streamed as "bash -s -- <args>", so a release-tarball install needs no checkout on either side.
	WhereScript = "script"
)

// Kind of a step.
const (
	KindAuto    = "auto"
	KindConfirm = "confirm"
	KindManual  = "manual"
)

// Migration modes.
const (
	ModeCopy    = "copy"     // one to one: files, DB, keys, certificates
	ModeFreshDB = "fresh_db" // the panel is set up on the new host; only the chosen data travels
	ModeDBOnly  = "db_only"  // the panel stays here, its database moves
)

// Database targets.
const (
	DBSame     = "same"     // whatever this host uses today (SQLite by default)
	DBPostgres = "postgres" // PostgreSQL on/at the new host; the DSN is supplied by the operator
)

// DNS strategies.
const (
	DNSSameProvider = "provider" // switch the A records through the provider stored in the panel
	DNSStub         = "stub"     // leave the names alone; reach the new host by IP for now
	DNSManual       = "manual"   // the wizard does not touch DNS at all
)

// Old-host dispositions.
const (
	OldKeep         = "keep"
	OldStop         = "stop"
	OldDecommission = "decommission"
)

// Auth kinds.
const (
	AuthKeyPath  = "key_path"  // an existing private key path on this host
	AuthKeyPaste = "key_paste" // a private key pasted into the form (stored encrypted)
	AuthPassword = "password"  // an OS login + password (stored encrypted)
)

// Install kinds.
const (
	InstallSystemd = "systemd"
	InstallDocker  = "docker"
)

// Answers is everything the wizard asked. It is stored as a row (host_migrations) and is the only
// input of Plan, so a plan can be regenerated byte for byte months later.
type Answers struct {
	Mode    string // ModeCopy | ModeFreshDB | ModeDBOnly
	Host    string // new host: IP or name
	Port    int    // SSH port
	User    string // SSH user
	Auth    string // AuthKeyPath | AuthKeyPaste | AuthPassword
	KeyPath string // when Auth == AuthKeyPath

	InstallKind string // InstallSystemd | InstallDocker

	DBMode string // DBSame | DBPostgres
	DBDSN  string // masked on render; never persisted in Answers

	NewHostname      string // tailnet hostname of the new panel host
	TailscaleAuthKey string // preauth key for `tailscale up`, optional

	DNSMode string // DNSSameProvider | DNSStub | DNSManual
	DNSTTL  int    // pre-roll TTL in seconds (default 300)

	OldHost string // OldKeep | OldStop | OldDecommission

	KeepNoiseKey bool // copy headscale's noise key (identity preserved)
	ReapplyACL   bool // push the ACL on the new host before switching DNS
	DedupeRules  bool // run the one-rule-per-target cleanup (B480)
	DerpMove     bool // the DERP relay moves with the panel
}

// Step is one row of host_migration_steps.
type Step struct {
	Phase    string // P0..P7
	Key      string // stable id, e.g. "p2.headscale_db"
	TitleKey string // i18n key: migrate.step.<TitleKey>.title
	WhyKey   string // i18n key for the failure-mode hint (may be empty)
	Kind     string
	Where    string
	Required bool
	Downtime bool   // the old services must be stopped for this step
	Command  string // shell for local/remote, "<local path> -> <remote path>" for copy,
	//                an action name for internal, the instruction text key for manual
	Verify string // shell that must exit 0, or the internal assertion name
	Note   string // extra i18n key for a warning shown before the step runs
}

// DefaultAnswers fills the values a fresh wizard starts from.
func DefaultAnswers() Answers {
	return Answers{
		Mode:         ModeCopy,
		Port:         22,
		User:         "root",
		Auth:         AuthKeyPath,
		InstallKind:  InstallSystemd,
		DBMode:       DBSame,
		DNSMode:      DNSManual,
		DNSTTL:       300,
		OldHost:      OldKeep,
		KeepNoiseKey: true,
		ReapplyACL:   true,
		DedupeRules:  true,
		DerpMove:     true,
	}
}

// Validate rejects an answer set that would produce a plan the wizard cannot keep honest.
//
// The checks are deliberately narrow: everything here is a fact the plan depends on, not a
// preference. A missing DNS strategy is rejected because "do nothing" is not one of the answers;
// an unknown mode is rejected because the step list would silently lose a phase.
func Validate(a Answers) error {
	var missing []string
	if strings.TrimSpace(a.Host) == "" {
		missing = append(missing, "target_host")
	}
	if a.Port < 1 || a.Port > 65535 {
		missing = append(missing, "target_port")
	}
	if strings.TrimSpace(a.User) == "" {
		missing = append(missing, "target_user")
	}
	switch a.Auth {
	case AuthKeyPath:
		if strings.TrimSpace(a.KeyPath) == "" {
			missing = append(missing, "auth_key_path")
		}
	case AuthKeyPaste, AuthPassword:
		// the secret itself is checked by the handler (it is not part of Answers)
	case "":
		missing = append(missing, "auth_kind")
	default:
		return fmt.Errorf("migrate: unknown auth kind %q", a.Auth)
	}
	switch a.Mode {
	case ModeCopy, ModeFreshDB, ModeDBOnly:
	case "":
		missing = append(missing, "mode")
	default:
		return fmt.Errorf("migrate: unknown mode %q", a.Mode)
	}
	switch a.DBMode {
	case DBSame:
	case DBPostgres:
		if strings.TrimSpace(a.DBDSN) == "" {
			missing = append(missing, "db_dsn")
		}
	case "":
		missing = append(missing, "db_mode")
	default:
		return fmt.Errorf("migrate: unknown db mode %q", a.DBMode)
	}
	switch a.DNSMode {
	case DNSSameProvider, DNSStub, DNSManual:
	case "":
		missing = append(missing, "dns_mode")
	default:
		return fmt.Errorf("migrate: unknown dns mode %q", a.DNSMode)
	}
	switch a.OldHost {
	case OldKeep, OldStop, OldDecommission:
	case "":
		missing = append(missing, "old_host")
	default:
		return fmt.Errorf("migrate: unknown old-host mode %q", a.OldHost)
	}
	if a.Mode == ModeCopy && strings.TrimSpace(a.NewHostname) == "" {
		missing = append(missing, "new_hostname")
	}
	if len(missing) > 0 {
		return fmt.Errorf("migrate: answers are incomplete: %s", strings.Join(missing, ", "))
	}
	return nil
}

// Plan builds the ordered step list for a set of answers.
//
// The order is the one that cost the migration its time, and the two rules that must not be
// rearranged are encoded here rather than left to the operator's memory:
//
//   - the SNAPSHOT (P0) comes before anything that touches the new host, because the old host can
//     become unreachable mid-flight (it did);
//   - the ACL and the tags (P5 vps.acl) come BEFORE the DNS switch (P5.vps.dns), because a switch
//     before them leaves untagged devices outside the rules for the whole window (B476/B477).
func Plan(a Answers) []Step {
	var steps []Step
	add := func(s Step) { steps = append(steps, s) }

	// ---------------- P0: prerequisites, and the snapshot of what travels ----------------
	add(Step{Phase: "P0", Key: "p0.inventory", TitleKey: "p0_inventory", WhyKey: "why_inventory",
		Kind: KindAuto, Where: WhereLocal, Required: true,
		Command: `for p in /var/lib/skygate /etc/skygate /etc/headscale /var/lib/headscale /var/lib/derper; do printf '%s\t' "$p"; [ -e "$p" ] && du -sh "$p" 2>/dev/null | cut -f1 || echo missing; done`,
		Verify:  `test -f /etc/skygate/skygate.env`})

	add(Step{Phase: "P0", Key: "p0.reach", TitleKey: "p0_reach", WhyKey: "why_reach",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `true`, Verify: `true`})

	add(Step{Phase: "P0", Key: "p0.host", TitleKey: "p0_host", WhyKey: "why_host",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `uname -m; . /etc/os-release 2>/dev/null; echo "$PRETTY_NAME"; systemctl --version | head -1; df -h / | tail -1; free -m | head -2; id -u`,
		Verify:  `systemctl --version >/dev/null && test "$(uname -m)" = "x86_64" && df -Pk / | awk 'NR==2 {exit !($4 > 5242880)}'`})

	add(Step{Phase: "P0", Key: "p0.ports", TitleKey: "p0_ports", WhyKey: "why_ports",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `ss -ltnup 2>/dev/null | grep -E ':(80|443|8080|8443|3478)\b' || echo 'ports free'`,
		Verify:  `! ss -ltnup 2>/dev/null | grep -qE ':(80|443|8443)\b'`})

	add(Step{Phase: "P0", Key: "p0.no_install", TitleKey: "p0_no_install", WhyKey: "why_no_install",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `ls -d /etc/skygate /etc/headscale 2>/dev/null || echo 'no previous install'`,
		Verify:  `test ! -e /etc/skygate && test ! -e /etc/headscale`})

	// The snapshot stops the panel: it is the only step in P0 that asks for confirmation.
	add(Step{Phase: "P0", Key: "p0.snapshot", TitleKey: "p0_snapshot", WhyKey: "why_snapshot",
		Kind: KindConfirm, Where: WhereLocal, Required: true, Downtime: true,
		Command: `set -e; S=/var/lib/skygate/migration-snapshots/$(date -u +%Y%m%dT%H%M%SZ); mkdir -p "$S"; for svc in skygate headscale; do systemctl is-active --quiet "$svc" && systemctl stop "$svc" || true; done; command -v sqlite3 >/dev/null && for db in /var/lib/skygate/skygate.db /var/lib/headscale/db.sqlite; do [ -f "$db" ] && sqlite3 "$db" 'PRAGMA wal_checkpoint(FULL);' || true; done; tar -czf "$S/data.tgz" -C / var/lib/skygate /etc/skygate /etc/headscale /var/lib/headscale 2>/dev/null || true; for svc in skygate headscale; do systemctl start "$svc" || true; done; echo "$S"`,
		Verify:  `ls /var/lib/skygate/migration-snapshots/*/data.tgz | tail -1`,
		Note:    "note_snapshot_stops_services"})

	// ---------------- P1: the new host's base ----------------
	add(Step{Phase: "P1", Key: "p1.base", TitleKey: "p1_base", WhyKey: "why_base",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `export DEBIAN_FRONTEND=noninteractive; apt-get update -qq && apt-get install -y -qq curl ca-certificates sqlite3 rsync ufw systemd-timesyncd >/dev/null && timedatectl set-ntp true || true`,
		Verify:  `command -v curl && command -v rsync && command -v sqlite3`})

	add(Step{Phase: "P1", Key: "p1.user", TitleKey: "p1_user", WhyKey: "why_user",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `id skygate >/dev/null 2>&1 || useradd --system --home /var/lib/skygate --shell /usr/sbin/nologin skygate; install -d -o skygate -g skygate -m 0750 /var/lib/skygate; install -d -o root -g skygate -m 0750 /etc/skygate`,
		Verify:  `id skygate && test -d /var/lib/skygate && test -d /etc/skygate`})

	add(Step{Phase: "P1", Key: "p1.firewall", TitleKey: "p1_firewall", WhyKey: "why_firewall",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `ufw allow 22/tcp >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; ufw allow 8080/tcp >/dev/null; ufw allow 8443/tcp >/dev/null; ufw allow 3478/udp >/dev/null; ufw --force enable >/dev/null; ufw status`,
		Verify:  `ufw status | grep -q '8443/tcp' && ufw status | grep -q '3478/udp'`})

	if strings.TrimSpace(a.NewHostname) != "" {
		add(Step{Phase: "P1", Key: "p1.tailscale", TitleKey: "p1_tailscale", WhyKey: "why_tailscale",
			Kind: KindAuto, Where: WhereRemote, Required: false,
			Command: `command -v tailscale >/dev/null || curl -fsSL https://tailscale.com/install.sh | sh; tailscale up --hostname="` + shellQuote(a.NewHostname) + `" --accept-routes=false --advertise-exit-node=false`,
			Verify:  `tailscale status >/dev/null`})
	}

	if a.InstallKind == InstallSystemd {
		add(Step{Phase: "P1", Key: "p1.skygate_install", TitleKey: "p1_skygate_install", WhyKey: "why_skygate_install",
			Kind: KindAuto, Where: WhereRemote, Required: a.Mode != ModeDBOnly,
			Command: `command -v skygate >/dev/null || curl -fsSL https://raw.githubusercontent.com/BarsSky/skygate/main/deploy/install-debian.sh | bash`,
			Verify:  `command -v skygate`})
	}

	// ---------------- P2: headscale ----------------
	if a.Mode != ModeDBOnly {
		add(Step{Phase: "P2", Key: "p2.headscale_stop", TitleKey: "p2_headscale_stop", WhyKey: "why_headscale_stop",
			Kind: KindConfirm, Where: WhereLocal, Required: true, Downtime: true,
			Command: `systemctl stop headscale 2>/dev/null || docker stop headscale >/dev/null 2>&1 || true; systemctl is-active headscale || true`,
			Verify:  `! systemctl is-active --quiet headscale`,
			Note:    "note_two_headscales"})

		add(Step{Phase: "P2", Key: "p2.headscale_config", TitleKey: "p2_headscale_config", WhyKey: "why_headscale_config",
			Kind: KindAuto, Where: WhereCopy, Required: true,
			Command: `/etc/headscale/config.yaml /etc/headscale/config.yaml`,
			Verify:  `test -f /etc/headscale/config.yaml`})

		add(Step{Phase: "P2", Key: "p2.headscale_db", TitleKey: "p2_headscale_db", WhyKey: "why_headscale_db",
			Kind: KindAuto, Where: WhereCopy, Required: true,
			Command: `/var/lib/headscale/db.sqlite /var/lib/headscale/db.sqlite`,
			Verify:  `test -f /var/lib/headscale/db.sqlite`})

		if a.KeepNoiseKey {
			add(Step{Phase: "P2", Key: "p2.noise_key", TitleKey: "p2_noise_key", WhyKey: "why_noise_key",
				Kind: KindAuto, Where: WhereCopy, Required: true,
				Command: `/var/lib/headscale/noise_private.key /var/lib/headscale/noise_private.key`,
				Verify:  `test -f /var/lib/headscale/noise_private.key`})
		}

		add(Step{Phase: "P2", Key: "p2.headscale_start", TitleKey: "p2_headscale_start", WhyKey: "why_headscale_start",
			Kind: KindAuto, Where: WhereRemote, Required: true,
			Command: `chown -R headscale:headscale /var/lib/headscale /etc/headscale 2>/dev/null || true; chmod 0640 /var/lib/headscale/db.sqlite; systemctl enable --now headscale; sleep 2; systemctl is-active headscale`,
			Verify:  `curl -fsS http://127.0.0.1:50444/health >/dev/null`})

		add(Step{Phase: "P2", Key: "p2.reregister", TitleKey: "p2_reregister", WhyKey: "why_reregister",
			Kind: KindManual, Where: WhereManual, Required: false,
			Command: "manual_register_confirm",
			Note:    "note_tags_dropped"})
	}

	// ---------------- P3: the panel ----------------
	add(Step{Phase: "P3", Key: "p3.env", TitleKey: "p3_env", WhyKey: "why_env",
		Kind: KindAuto, Where: WhereCopy, Required: a.Mode != ModeDBOnly,
		Command: `/etc/skygate/skygate.env /etc/skygate/skygate.env`,
		Verify:  `test -f /etc/skygate/skygate.env`,
		Note:    "note_env_secrets"})

	if a.Mode == ModeCopy {
		add(Step{Phase: "P3", Key: "p3.data", TitleKey: "p3_data", WhyKey: "why_data",
			Kind: KindConfirm, Where: WhereCopy, Required: true, Downtime: true,
			Command: `/var/lib/skygate /var/lib/skygate`,
			Verify:  `test -f /var/lib/skygate/skygate.db`,
			Note:    "note_data_dir_overwrite"})
	}

	if a.DBMode == DBPostgres {
		add(Step{Phase: "P3", Key: "p3.db_convert", TitleKey: "p3_db_convert", WhyKey: "why_db_convert",
			Kind: KindConfirm, Where: WhereLocal, Required: true, Downtime: true,
			Command: `skygate db-migrate --from sqlite:/var/lib/skygate/skygate.db --to "$SKYGATE_MIGRATION_TARGET_DSN"`,
			Verify:  `true`,
			Note:    "note_pg_weight"})
	}

	add(Step{Phase: "P3", Key: "p3.start", TitleKey: "p3_start", WhyKey: "why_start",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `systemctl enable --now skygate; sleep 3; systemctl is-active skygate`,
		Verify:  `curl -fsS http://127.0.0.1:8080/healthz | grep -q '"status":"ok"'`})

	add(Step{Phase: "P3", Key: "p3.migrate", TitleKey: "p3_migrate", WhyKey: "why_migrate",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `skygate migrate status | tail -1`,
		Verify:  `skygate migrate status | grep -q 'pending=0'`})

	add(Step{Phase: "P3", Key: "p3.readyz", TitleKey: "p3_readyz", WhyKey: "why_readyz",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `curl -fsS http://127.0.0.1:8080/readyz`,
		Verify:  `curl -fsS http://127.0.0.1:8080/readyz | grep -q '"healthy":true'`})

	// ---------------- P4: DERP ----------------
	if a.DerpMove && a.Mode != ModeDBOnly {
		add(Step{Phase: "P4", Key: "p4.derper", TitleKey: "p4_derper", WhyKey: "why_derper",
			Kind: KindAuto, Where: WhereRemote, Required: true,
			Command: `command -v derper >/dev/null || (command -v go >/dev/null && GO111MODULE=on go install tailscale.com/cmd/derper@latest); systemctl enable --now derper 2>/dev/null || true; systemctl is-active derper || true`,
			Verify:  `ss -ltnp 2>/dev/null | grep -q ':8443'`})

		// The three derp settings (probe host, debug URL, relay URL) belong to the panel's own page:
		// they are installation-wide, not per-run, and /admin/derp already validates them. The wizard
		// says so instead of writing global_settings behind the operator's back.
		add(Step{Phase: "P4", Key: "p4.settings", TitleKey: "p4_settings", WhyKey: "why_derp_settings",
			Kind: KindManual, Where: WhereManual, Required: false,
			Command: "manual_derp_settings",
			Note:    "note_derp_settings"})

		add(Step{Phase: "P4", Key: "p4.cert", TitleKey: "p4_cert", WhyKey: "why_cert",
			Kind: KindConfirm, Where: WhereScript, Required: true,
			Command: `derper-cert-sync --install`,
			Verify:  `systemctl list-timers --all 2>/dev/null | grep -q derper-cert-sync`,
			Note:    "note_cert_chain"})

		// Registering the relay is the existing B164 page: it owns the region id, the sort order and
		// the reachability probe, and a wizard that invented those numbers would be how an
		// installation ends up with a relay nobody can find. So the step is MANUAL and points there;
		// the probe that proves it works is separate and automatic (p6.derp).
		add(Step{Phase: "P4", Key: "p4.relay_row", TitleKey: "p4_relay_row", WhyKey: "why_relay_row",
			Kind: KindManual, Where: WhereManual, Required: false,
			Command: "manual_derp_relay_register",
			Note:    "note_relay_register"})
	}

	// ---------------- P5: tags, ACL, DNS, ACME ----------------
	add(Step{Phase: "P5", Key: "p5.tags", TitleKey: "p5_tags", WhyKey: "why_tags",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `skygate --version >/dev/null; echo 'waiting for tag reconcile'; sleep 5; true`,
		Verify:  "internal_tags_present"})

	if a.ReapplyACL {
		add(Step{Phase: "P5", Key: "p5.acl", TitleKey: "p5_acl", WhyKey: "why_acl",
			Kind: KindAuto, Where: WhereRemote, Required: true,
			Command: `skygate acl-apply`,
			Verify:  "internal_policy_equivalent",
			Note:    "note_acl_before_dns"})
	}

	if a.DedupeRules {
		add(Step{Phase: "P5", Key: "p5.dedupe", TitleKey: "p5_dedupe", WhyKey: "why_dedupe",
			Kind: KindAuto, Where: WhereScript, Required: false,
			Command: `b480-dup-cleanup`,
			Verify:  `true`})
	}

	switch a.DNSMode {
	case DNSSameProvider:
		add(Step{Phase: "P5", Key: "p5.dns", TitleKey: "p5_dns", WhyKey: "why_dns",
			Kind: KindConfirm, Where: WhereLocal, Required: true,
			Command: `skygate dns-records && skygate dns-set-a --name="$SKYGATE_PANEL_NAMES" --ip=` + dnsTarget(a) + ` --ttl=` + fmt.Sprint(dnsTTL(a)),
			Verify:  `skygate dns-records`,
			Note:    "note_ttl"})
	case DNSStub:
		add(Step{Phase: "P5", Key: "p5.dns", TitleKey: "p5_dns_stub", WhyKey: "why_dns_stub",
			Kind: KindManual, Where: WhereManual, Required: false,
			Command: "manual_dns_stub",
			Note:    "note_acme_needs_dns"})
	default:
		add(Step{Phase: "P5", Key: "p5.dns", TitleKey: "p5_dns_manual", WhyKey: "why_dns_manual",
			Kind: KindManual, Where: WhereManual, Required: false,
			Command: "manual_dns",
			Note:    "note_ttl"})
	}

	add(Step{Phase: "P5", Key: "p5.acme", TitleKey: "p5_acme", WhyKey: "why_acme",
		Kind: KindAuto, Where: WhereRemote, Required: false,
		Command: `for i in $(seq 1 60); do echo | openssl s_client -servername "$SKYGATE_PANEL_HOST" -connect "$SKYGATE_PANEL_HOST":443 2>/dev/null | grep -q 'Verify return code: 0' && exit 0; sleep 10; done; exit 1`,
		Verify:  `echo | openssl s_client -connect 127.0.0.1:443 2>/dev/null | grep -q 'Verify return code: 0'`})

	// ---------------- P6: verification ----------------
	add(Step{Phase: "P6", Key: "p6.health", TitleKey: "p6_health", WhyKey: "why_health",
		Kind: KindAuto, Where: WhereRemote, Required: true,
		Command: `curl -fsS http://127.0.0.1:8080/healthz`,
		Verify:  `curl -fsS http://127.0.0.1:8080/healthz | grep -q '"status":"ok"'`})

	add(Step{Phase: "P6", Key: "p6.nodes", TitleKey: "p6_nodes", WhyKey: "why_nodes",
		Kind: KindAuto, Where: WhereInternal, Required: true,
		Command: "internal_nodes_online",
		Verify:  "internal_nodes_online"})

	add(Step{Phase: "P6", Key: "p6.routes", TitleKey: "p6_routes", WhyKey: "why_routes",
		Kind: KindAuto, Where: WhereInternal, Required: true,
		Command: "internal_routes_converged",
		Verify:  "internal_routes_converged"})

	if a.DerpMove && a.Mode != ModeDBOnly {
		add(Step{Phase: "P6", Key: "p6.derp", TitleKey: "p6_derp", WhyKey: "why_derp_probe",
			Kind: KindAuto, Where: WhereInternal, Required: true,
			Command: "internal_derp_probe",
			Verify:  "external_derp_probe_101"})
	}

	add(Step{Phase: "P6", Key: "p6.verify", TitleKey: "p6_verify", WhyKey: "why_verify",
		Kind: KindAuto, Where: WhereScript, Required: false,
		Command: `verify-migration`,
		Verify:  `true`})

	add(Step{Phase: "P6", Key: "p6.client", TitleKey: "p6_client", WhyKey: "why_client",
		Kind: KindManual, Where: WhereManual, Required: true,
		Command: "manual_client_check",
		Note:    "note_client_check"})

	// ---------------- P7: the old host ----------------
	switch a.OldHost {
	case OldStop:
		add(Step{Phase: "P7", Key: "p7.stop", TitleKey: "p7_stop", WhyKey: "why_stop_old",
			Kind: KindConfirm, Where: WhereLocal, Required: false, Downtime: true,
			Command: `systemctl stop skygate headscale derper 2>/dev/null || true; echo stopped`,
			Verify:  `true`})
	case OldDecommission:
		add(Step{Phase: "P7", Key: "p7.decommission", TitleKey: "p7_decommission", WhyKey: "why_decommission",
			Kind: KindManual, Where: WhereManual, Required: false,
			Command: "manual_decommission",
			Note:    "note_decommission"})
	}

	return steps
}

// dnsTTL keeps the pre-roll TTL inside the range a provider will accept, so a wrong answer cannot
// turn into a rejected API call that looks like a network problem.
func dnsTTL(a Answers) int {
	if a.DNSTTL >= 60 && a.DNSTTL <= 86400 {
		return a.DNSTTL
	}
	return 300
}

// dnsTarget renders the address the DNS switch should point at.
//
// The wizard asks for one thing — where the new panel is — and that answer is an address in the
// common case, so it is substituted literally and the step is self-contained. When the operator
// named the new host (not an address), the step keeps the panel-side variable instead of guessing:
// a wrong IP written into a live zone is not a failure the operator can undo with a click.
func dnsTarget(a Answers) string {
	if ip, err := netip.ParseAddr(strings.TrimSpace(a.Host)); err == nil {
		return shellQuote(ip.String())
	}
	return `"$SKYGATE_NEW_IP"`
}

// shellQuote makes an answer safe to interpolate into a step command.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// RequiredSteps returns only the steps whose failure must stop the run.
func RequiredSteps(steps []Step) []Step {
	out := make([]Step, 0, len(steps))
	for _, s := range steps {
		if s.Required {
			out = append(out, s)
		}
	}
	return out
}

// Phases lists the phases in plan order with their step keys — the wizard's plan page renders this
// as a folded per-phase list instead of one 35-row table.
func Phases(steps []Step) []Phase {
	var out []Phase
	for _, s := range steps {
		if len(out) == 0 || out[len(out)-1].Name != s.Phase {
			out = append(out, Phase{Name: s.Phase})
		}
		out[len(out)-1].Steps = append(out[len(out)-1].Steps, s)
	}
	return out
}

// Phase groups the steps of one phase.
type Phase struct {
	Name  string
	Steps []Step
}
