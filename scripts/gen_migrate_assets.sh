#!/usr/bin/env bash
# ============================================================================
# scripts/gen_migrate_assets.sh — B487
#
# THE MIGRATION WIZARD MUST NOT DEPEND ON A CHECKOUT IT CANNOT SEE.
#
# The plan's steps used to run `bash /opt/skygate/scripts/…` and `bash /opt/skygate/deploy/derper-cert-sync.sh`.
# A native (systemd) install is a RELEASE TARBALL: it has no `/opt/skygate` checkout at all, so those
# three steps would fail with "No such file or directory" on exactly the installation the wizard exists
# for. The helpers are needed on the TARGET host, and the only artefact that is always present there is
# the panel binary — so the helpers are EMBEDDED into it.
#
# WHY A GENERATED FILE AND BASE64
#
#   - one source of truth: the scripts stay where they are (deploy/, scripts/); this file only mirrors
#     them, and contract B487 fails when the mirror drifts from the sources;
#   - base64 avoids every escaping trap of Go literals (the scripts contain backticks, quotes, `$`,
#     and Windows checkouts have CRLF) — the executor decodes it and streams the script to `bash -s`.
#
# Run from the repository root; the output path is fixed on purpose.
# ============================================================================
set -euo pipefail

OUT=internal/migrate/assets_gen.go
mkdir -p "$(dirname "$OUT")"

b64() { # file → one base64 line, no wrapping
  base64 < "$1" | tr -d '\n'
}

{
  cat <<'GO'
// Code generated by scripts/gen_migrate_assets.sh — DO NOT EDIT.
//
// These are the migration wizard's helper scripts, embedded so a native (release-tarball) install can
// run them on the TARGET host without a checkout: the panel binary is the only artefact guaranteed to
// be there. Contract B487 fails when this file drifts from the sources it mirrors.
package migrate

// Asset is one embedded helper: the name the plan uses, the file it mirrors and its base64 body.
type Asset struct {
	// Name is what a plan step names, e.g. "derper-cert-sync".
	Name string
	// Source is the repository file this asset mirrors (for the drift contract).
	Source string
	// B64 is the script, base64-encoded (the sources contain backticks, quotes and $).
	B64 string
}

// migrateAssets lists every embedded helper. Order is stable so the generated file is diffable.
var migrateAssets = []Asset{
GO
  for spec in \
    "derper-cert-sync:deploy/derper-cert-sync.sh" \
    "verify-migration:scripts/verify_migration.sh" \
    "b480-dup-cleanup:scripts/b480_dup_rule_cleanup.sh"; do
    name="${spec%%:*}"
    src="${spec#*:}"
    [ -f "$src" ] || { echo "gen_migrate_assets: missing $src" >&2; exit 1; }
    printf '\t{Name: "%s", Source: "%s", B64: "%s"},\n' "$name" "$src" "$(b64 "$src")"
  done
  cat <<'GO'
}
GO
} > "$OUT"

echo "gen_migrate_assets: wrote $OUT ($(wc -c < "$OUT") bytes, $(grep -c 'B64:' "$OUT") asset(s))"
